// Build public/data/quests.json from the planning Page export (docs/phase1/quests-raw.json)
// plus scripts/quests/rules.mjs (prerequisites) and scripts/quests/playable.mjs (steps for batch 1).
// node scripts/build-quests.mjs
import fs from 'node:fs';
import { REQ, HIDDEN, WHEN, NEEDS_ITEM, DISTANCE_ONLY, GROUND, SONGS } from './quests/rules.mjs';
import { PLAYABLE as PLAYABLE_1 } from './quests/playable.mjs';
import { PLAYABLE_1B, SONG_OF } from './quests/playable-1b.mjs';

const PLAYABLE = { ...PLAYABLE_1, ...PLAYABLE_1B };

const raw = JSON.parse(fs.readFileSync('docs/phase1/quests-raw.json', 'utf8'));
const MAIN = new Set(raw.main);

/** who text → roles allowed to act ('m' 族男, 'f' 族女, 't' 旅人) */
function rolesOf(who) {
  if (/任一人|全隊|待確認/.test(who)) return ['m', 'f', 't'];
  const lead = who.split(/；|，/)[0];
  const r = [];
  if (lead.includes('族男') || lead.includes('族人')) r.push('m');
  if (lead.includes('族女') || lead.includes('族人')) r.push('f');
  if (lead.includes('旅人')) r.push('t');
  return r.length ? r : ['m', 'f', 't'];
}

/** party presence needed (n ≥ 2), from the 合作 text */
function needOf(q) {
  if (q.n < 2) return undefined;
  if (q.n === 3) return ['m', 'f', 't'];
  const c = q.coop;
  if (/族男＋族女/.test(c)) return ['m', 'f'];
  if (/族女＋旅人|旅人＋族女/.test(c)) return ['f', 't'];
  if (/旅人＋族男|族男＋旅人/.test(c)) return ['t', 'm'];
  if (/旅人＋/.test(c) || /族人＋旅人/.test(c)) return ['t', 'mf'];
  return ['mf', 't'];
}

const PHOTO_SPOTS = {
  twinlions: { landmark: 'twinlions', r: 16 },
  battleship: { landmark: 'battleship', r: 18 },
  qingqing: { landmark: 'qingqing', r: 10 },
  harbor: { place: 'harbor', r: 9 },
  airport: { place: 'airport', r: 9 },
};

const quests = raw.quests.map((q) => {
  const dive = q.id.startsWith('U'); // underwater: 相簿與水下 line, modern recreation → anyone (U3 traveller)
  const line = q.group === 'photo' || dive ? 'photo' : MAIN.has(q.id) ? 'main' : 'side';
  const roles = q.group === 'photo' && !dive ? ['t'] : GROUND[q.id] === 'fishing' ? ['m'] : rolesOf(q.who);
  const p = PLAYABLE[q.id];
  let steps;
  let hint;
  if (p?.photo) {
    const s = PHOTO_SPOTS[p.photo];
    steps = [{ kind: 'photo', spot: p.photo, r: s.r, actor: ['t'], text: `旅人用相機拍下：${q.name.replace(/^拍/, '')}` }];
    hint = p.hint;
  } else if (p) {
    steps = p.steps;
    hint = p.hint;
  } else {
    steps = [{ kind: 'placeholder', text: '這個任務的內容會在後續版本加入。' }];
    hint = { tier: 'direct', from: '筆記本', zh: '這個任務的內容會在後續版本加入。' };
  }
  const out = {
    id: q.id,
    line,
    group: q.group,
    name: { zh: q.name.replace(/（第一次去有 ❗）$/, ''), en: '' }, // the ❗ note is a design note, the marker shows it in game
    roles,
    n: q.n,
    need: needOf(q),
    text: { who: q.who, coop: q.coop, season: q.season, pre: q.pre, unlock: q.unlock, kind: raw.kind[q.id] ?? '' },
    req: REQ[q.id],
    steps,
    hint,
    playable: !!p,
  };
  if (HIDDEN.has(q.id)) out.hidden = true;
  if (WHEN[q.id]) out.when = WHEN[q.id];
  if (NEEDS_ITEM[q.id]) out.needsItem = NEEDS_ITEM[q.id];
  if (DISTANCE_ONLY[q.id] !== undefined) out.distanceOnly = true;
  if (GROUND[q.id]) out.ground = GROUND[q.id];
  if (SONG_OF[q.id]) out.song = SONG_OF[q.id];
  if (!out.req) throw new Error(`no req for ${q.id}`);
  return out;
});

// sanity: every quest id referenced by a req exists; main quests only depend on main quests
const ids = new Set(quests.map((q) => q.id));
const byId = Object.fromEntries(quests.map((q) => [q.id, q]));
const refs = (r) => (typeof r === 'string' ? [r] : r.all ? r.all.flatMap(refs) : r.any ? r.any.flatMap(refs) : []);
for (const q of quests) {
  for (const r of refs(q.req)) {
    if (!ids.has(r)) throw new Error(`${q.id} requires unknown ${r}`);
    if (q.line === 'main' && byId[r].line !== 'main') throw new Error(`main ${q.id} depends on non-main ${r}`);
  }
}

const data = {
  notes: `Generated by scripts/build-quests.mjs from the planning Page (${quests.length} quests). zh-TW text is from the Page; English is a stub. Tao phrases: sourced 暫定 table only.`,
  roles: {
    m: { zh: '族男', icon: '男' },
    f: { zh: '族女', icon: '女' },
    t: { zh: '旅人', icon: '旅' },
  },
  respect: [
    { id: 'first', zh: '初訪' },
    { id: 'learning', zh: '學習中' },
    { id: 'trusted', zh: '受信任' },
    { id: 'friend', zh: '朋友' },
  ],
  items: {
    headlamp: { zh: '頭燈' },
    sunscreen: { zh: '防曬' },
    water: { zh: '飲水' },
    lifejacket: { zh: '救生衣' },
  },
  /** Tao-only hint phrases (暫定; sources kept here, never shown in the dialogue) */
  phrases: {
    ikongo: { tao: 'ikongo yamyan do wawa?', zh: '海裡有什麼呢？', source: '族語 E 樂園第 5 階第 9 課（暫定）', words: ['wawa'] },
    mangay: { tao: 'mangay ko pa kalahen.', zh: '我先去找一找。', source: '族語 E 樂園第 7 階第 7 課（暫定）', words: [] },
  },
  photoSpots: PHOTO_SPOTS,
  songs: SONGS,
  quests,
};
// S6 (audit): build-time referential check — fail on broken references, warn on flags / counters nothing gives
{
  const errs = [];
  const warns = [];
  const npcIds = new Set(JSON.parse(fs.readFileSync('public/data/npcs.json', 'utf8')).npcs.map((n) => n.id));
  const placeIds = new Set(Object.keys(JSON.parse(fs.readFileSync('public/data/places.json', 'utf8')).places));
  const glossIds = new Set(JSON.parse(fs.readFileSync('public/data/glossary.json', 'utf8')).entries.map((e) => e.id));
  // places game.ts derives at runtime (shops / host family / dive spots)
  for (const id of ['yayo_shop', 'yayo_school', 'rental', 'dive_shop', 'hen_rock_bay', 'yayo_dive', 'host_home', 'host_taro', 'host_weave']) placeIds.add(id);
  const ORIGINS = ['yayo', 'iraraley', 'iranmeylek', 'ivalino', 'imorod', 'iratay'];
  const respectIds = new Set(data.respect.map((r) => r.id));
  const given = { flags: new Set(['party_created', 'u1_by_t', 'tao_hint_heard']), items: new Set(), counters: new Set(['words', 'photos']) };
  for (const q of quests) for (const st of q.steps) {
    st.gives?.flags?.forEach((f) => given.flags.add(f));
    st.gives?.items?.forEach((i) => given.items.add(i));
    Object.keys(st.gives?.counter ?? {}).forEach((c) => given.counters.add(c));
  }
  const walk = (r, where) => {
    if (typeof r === 'string') { if (!ids.has(r)) errs.push(`${where}: unknown quest ${r}`); return; }
    if (!r || typeof r !== 'object') { errs.push(`${where}: bad req`); return; }
    if (r.all) return r.all.forEach((x) => walk(x, where));
    if (r.any) { if ((r.n ?? 1) > r.any.length) errs.push(`${where}: n ${r.n} > ${r.any.length} options`); return r.any.forEach((x) => walk(x, where)); }
    if ('respect' in r && !respectIds.has(r.respect)) errs.push(`${where}: unknown respect ${r.respect}`);
    if ('flag' in r && !given.flags.has(r.flag) && !r.flag.startsWith('met_npc_')) warns.push(`${where}: flag ${r.flag} is never given`);
    if ('flag' in r && r.flag.startsWith('met_npc_') && !npcIds.has(r.flag.slice(8))) errs.push(`${where}: ${r.flag} names an unknown npc`);
    if ('count' in r && !given.counters.has(r.count)) warns.push(`${where}: counter ${r.count} is never given`);
  };
  for (const q of quests) {
    walk(q.req, q.id);
    if (q.needsItem && !(q.needsItem.item in data.items)) errs.push(`${q.id}: unknown item ${q.needsItem.item}`);
    if (q.needsItem && !given.items.has(q.needsItem.item)) errs.push(`${q.id}: item ${q.needsItem.item} is never given`);
    if (q.hint?.phrase && !data.phrases[q.hint.phrase]) errs.push(`${q.id}: unknown phrase ${q.hint.phrase}`);
    if (q.song && !data.songs[q.song]) errs.push(`${q.id}: unknown song ${q.song}`);
    if (q.playable && q.steps.every((st) => st.kind === 'placeholder')) errs.push(`${q.id}: playable but only placeholder steps`);
    q.steps.forEach((st, i) => {
      const w = `${q.id}#${i}`;
      if (st.until) walk(st.until, w);
      if (st.kind === 'talk') {
        const need = st.npc === '@host' ? ORIGINS.map((o) => `elder_${o}`) : [st.npc];
        for (const n of need) if (!npcIds.has(n)) errs.push(`${w}: unknown npc ${n}`);
      }
      if (st.kind === 'spot' && !placeIds.has(st.spot)) errs.push(`${w}: unknown spot ${st.spot}`);
      if (st.kind === 'photo' && !data.photoSpots[st.spot]) errs.push(`${w}: unknown photo spot ${st.spot}`);
      if (st.gives?.respect && !respectIds.has(st.gives.respect)) errs.push(`${w}: gives unknown respect ${st.gives.respect}`);
      st.gives?.items?.forEach((it) => { if (!(it in data.items)) errs.push(`${w}: gives unknown item ${it}`); });
      st.gives?.glossary?.forEach((g) => { if (!glossIds.has(g)) errs.push(`${w}: unknown glossary id ${g}`); });
      // auto steps with lines are replayed by Game.runPendingAutoLines (audit M1), so they are allowed
    });
  }
  // cycles in quest-id prerequisites
  const state = new Map();
  const visit = (id, path) => {
    if (state.get(id) === 2) return;
    if (state.get(id) === 1) { errs.push(`cycle: ${[...path, id].join(' → ')}`); return; }
    state.set(id, 1);
    for (const r of refs(byId[id].req)) if (ids.has(r)) visit(r, [...path, id]);
    state.set(id, 2);
  };
  for (const q of quests) visit(q.id, []);
  if (warns.length) console.warn(`quests check: ${warns.length} warning(s) (expected placeholders)\n  ` + warns.join('\n  '));
  if (errs.length) { console.error('quests check FAILED:\n  ' + errs.join('\n  ')); process.exit(1); }
}
fs.writeFileSync('public/data/quests.json', JSON.stringify(data, null, 1) + '\n');
const c = { main: 0, side: 0, photo: 0, playable: 0 };
for (const q of quests) { c[q.line]++; if (q.playable) c.playable++; }
console.log('quests.json', quests.length, c);
